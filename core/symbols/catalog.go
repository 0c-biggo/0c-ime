// Locate 回傳符號所在的分頁與位置；不在目錄裡時 ok 為 false。
func Locate(text string) (tab, index int, ok bool) {
	for t, tb := range Tabs {
		if i := slices.Index(tb.Items, text); i >= 0 {
			return t, i, true
		}
	}
	return 0, 0, false
}

// Contains 回報 text 是不是選單裡的符號。
func Contains(text string) bool {
	_, _, ok := Locate(text)
	return ok
}

// ID 是符號的穩定候選 ID：IDBase 加上它在所有固定分頁裡的序號；不在目錄裡時回傳 -1。
func ID(text string) int {
	n := 0
	for _, tb := range Tabs {
		if i := slices.Index(tb.Items, text); i >= 0 {
			return IDBase + n + i
		}
		n += len(tb.Items)
	}
	return -1
}

// CleanRecent 丟掉不在目錄裡的與重複的項目，最多 MaxRecent 項，不排序、不保存任意文字。
// 回傳值不與目錄或輸入共用。
func CleanRecent(recent []string) []string {
	var out []string
	for _, text := range recent {
		if Contains(text) && !slices.Contains(out, text) {
			out = append(out, text)
			if len(out) == MaxRecent {
				break
			}
		}
	}
	return out
}
